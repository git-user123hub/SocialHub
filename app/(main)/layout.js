export default async function MainRootLayout({ children, modal }) {
  const supabase = serverDB();

  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser();

  if (!user || authError) {
    redirect("/auth/login");
  }

  let userProfile;
  let dark_mode;

  if (user) {
    let { data: user_profile } = await supabase
      .from("user_profile")
      .select("*")
      .eq("id", user.id)
      .maybeSingle();

    userProfile = user_profile;

    const { data: darkMode, error } = await supabase
      .from("dark_mode")
      .select("*")
      .eq("darked_by", user.id)
      .maybeSingle();

    dark_mode = darkMode;
  }

  return (
    <html
      lang="en"
      className={`${dark_mode?.dark_status ? "dark" : "light"} supports-[overflow-wrap:anywhere]:[overflow-wrap:anywhere] supports-[not(overflow-wrap:anywhere)]:[word-break:normal]`}
      suppressHydrationWarning={true}
    >
      <body
        className="antialiased flex bg-mainClr"
        suppressHydrationWarning={true}
      >
        <PathTracker />
        <MainSvg />

        <MainContextProvider
          initialUser={user}
          initialProfile={userProfile}
          initialDarkStatus={dark_mode}
        >
          <ScrollManager />

          <Suspense fallback={null}>
            <Sidebar />
          </Suspense>

          <main className="flex w-full mt-11 lg:mt-0">
            <div className="md:mx-auto w-full lg:w-[74%] flex justify-center">
              <Suspense fallback={null}>{children}</Suspense>
            </div>
          </main>

          <Suspense fallback={null}>{modal}</Suspense>
        </MainContextProvider>

        <ToasterWrapper />
      </body>
    </html>
  );
}
